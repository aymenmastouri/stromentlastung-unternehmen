-- Unternehmensregister: Dienststellen, Unternehmen, Zuordnungen (Fachkonzept Kap. 4).
CREATE TABLE hauptzollamt (
    kennung VARCHAR(8) PRIMARY KEY,
    name    VARCHAR(120) NOT NULL,
    sitz    VARCHAR(120) NOT NULL,
    iban    VARCHAR(34)  NOT NULL
);

CREATE TABLE unternehmen (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kennung              VARCHAR(12)  NOT NULL UNIQUE,
    name                 VARCHAR(200) NOT NULL,
    rechtsform           VARCHAR(40)  NOT NULL,
    strasse              VARCHAR(200) NOT NULL,
    plz                  VARCHAR(5)   NOT NULL,
    ort                  VARCHAR(120) NOT NULL,
    hauptzollamt_kennung VARCHAR(8)   NOT NULL REFERENCES hauptzollamt (kennung),
    kontoverbindung      VARCHAR(120),
    angelegt_am          TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE zuordnung (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unternehmen_kennung     VARCHAR(12) NOT NULL REFERENCES unternehmen (kennung),
    entnahmejahr            INT         NOT NULL,
    beantragter_abschnitt   VARCHAR(12) NOT NULL,
    massgebender_zeitraum   VARCHAR(16) NOT NULL,
    schwerpunktkriterium    VARCHAR(24),
    taetigkeitsbeschreibung VARCHAR(2000),
    zustand                 VARCHAR(12) NOT NULL,
    entschiedener_abschnitt VARCHAR(12),
    begruendung             VARCHAR(2000),
    entschieden_von         VARCHAR(120),
    entschieden_am          TIMESTAMP WITH TIME ZONE,
    beantragt_am            TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_zuordnung_unternehmen_jahr UNIQUE (unternehmen_kennung, entnahmejahr)
);
